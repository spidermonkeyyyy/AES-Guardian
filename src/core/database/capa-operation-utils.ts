export type CapaPayloadForHash = {
  title: string;
  description: string;
  action_type: string;
  contributing_factor: string;
  rationale: string;
  surveillance_reference: string | null;
  target_date: string | null;
};

export function canonicalCapaPayload(payload: CapaPayloadForHash): string {
  return JSON.stringify({
    title: payload.title,
    description: payload.description,
    action_type: payload.action_type,
    contributing_factor: payload.contributing_factor,
    rationale: payload.rationale,
    surveillance_reference: payload.surveillance_reference,
    target_date: payload.target_date,
  });
}

function rotateRight(value: number, amount: number): number {
  return (value >>> amount) | (value << (32 - amount));
}

