export function sha256Hex(input: string): string {
  const bytes: number[] = [];
  for (let i = 0; i < input.length; i++) {
    let code = input.charCodeAt(i);
    if (code < 0x80) {
      bytes.push(code);
    } else if (code < 0x800) {
      bytes.push(0xc0 | (code >> 6), 0x80 | (code & 0x3f));
    } else if (code >= 0xd800 && code <= 0xdbff) {
      const next = input.charCodeAt(++i);
      code = 0x10000 + ((code - 0xd800) << 10) + (next - 0xdc00);
      bytes.push(
        0xf0 | (code >> 18),
        0x80 | ((code >> 12) & 0x3f),
        0x80 | ((code >> 6) & 0x3f),
        0x80 | (code & 0x3f),
      );
    } else {
      bytes.push(
        0xe0 | (code >> 12),
        0x80 | ((code >> 6) & 0x3f),
        0x80 | (code & 0x3f),
      );
    }
  }

  const bitLength = bytes.length * 8;
  bytes.push(0x80);
  while (bytes.length % 64 !== 56) bytes.push(0);
  for (let i = 7; i >= 0; i--) bytes.push((bitLength / (2 ** (8 * i))) & 0xff);

  let h0 = 0x6a09e667;
  let h1 = 0xbb67ae85;
  let h2 = 0x3c6ef372;
  let h3 = 0xa54ff53a;
  let h4 = 0x510e527f;
  let h5 = 0x9b05688c;
  let h6 = 0x1f83d9ab;
  let h7 = 0x5be0cd19;

  for (let offset = 0; offset < bytes.length; offset += 64) {
    const words = new Array<number>(64);
    for (let i = 0; i < 16; i++) {
      const p = offset + i * 4;
      words[i] =
        ((bytes[p] << 24) | (bytes[p + 1] << 16) |
          (bytes[p + 2] << 8) | bytes[p + 3]) >>> 0;
    }
    for (let i = 16; i < 64; i++) {
      const s0 =
        rotateRight(words[i - 15], 7) ^
        rotateRight(words[i - 15], 18) ^
        (words[i - 15] >>> 3);
      const s1 =
        rotateRight(words[i - 2], 17) ^
        rotateRight(words[i - 2], 19) ^
        (words[i - 2] >>> 10);
      words[i] = (words[i - 16] + s0 + words[i - 7] + s1) >>> 0;
    }

    let a = h0, b = h1, c = h2, d = h3, e = h4, f = h5, g = h6, hh = h7;
    for (let i = 0; i < 64; i++) {
      const s1 = rotateRight(e, 6) ^ rotateRight(e, 11) ^ rotateRight(e, 25);
      const ch = (e & f) ^ (~e & g);
      const temp1 = (hh + s1 + ch + SHA256_CONSTANTS[i] + words[i]) >>> 0;
      const s0 = rotateRight(a, 2) ^ rotateRight(a, 13) ^ rotateRight(a, 22);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const temp2 = (s0 + maj) >>> 0;
      hh = g; g = f; f = e; e = (d + temp1) >>> 0;
      d = c; c = b; b = a; a = (temp1 + temp2) >>> 0;
    }
    h0 = (h0 + a) >>> 0;
    h1 = (h1 + b) >>> 0;
    h2 = (h2 + c) >>> 0;
    h3 = (h3 + d) >>> 0;
    h4 = (h4 + e) >>> 0;
    h5 = (h5 + f) >>> 0;
    h6 = (h6 + g) >>> 0;
    h7 = (h7 + hh) >>> 0;
  }

  return [h0, h1, h2, h3, h4, h5, h6, h7]
    .map(value => value.toString(16).padStart(8, '0'))
    .join('');
}

export class CapaOperationEntropyUnavailableError extends Error {
  constructor() {
    super('Secure cryptographic randomness is unavailable; no CAPA operation was created.');
    this.name = 'CapaOperationEntropyUnavailableError';
  }
}

export function isValidCapaOperationId(operationId: string): boolean {
  return /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(
    operationId,
  );
}

export class CapaOperationIdCollisionError extends Error {
  readonly operationId: string;

  constructor(operationId: string) {
    super('A new CAPA operation ID collided with an existing operation.');
    this.name = 'CapaOperationIdCollisionError';
    this.operationId = operationId;
  }
}

export function createCapaOperationId(): string {
  const cryptoObject = (globalThis as any)?.crypto;
  if (typeof cryptoObject?.randomUUID === 'function') {
    try {
      const operationId = cryptoObject.randomUUID();
      if (typeof operationId === 'string' && isValidCapaOperationId(operationId)) {
        return operationId;
      }
      throw new CapaOperationEntropyUnavailableError();
    } catch {
      throw new CapaOperationEntropyUnavailableError();
    }
  }
  if (typeof cryptoObject?.getRandomValues === 'function') {
    try {
      const bytes = new Uint8Array(16);
      const output = cryptoObject.getRandomValues(bytes);
      if (
        !output ||
        output.length !== 16 ||
        Array.from(output).every(value => value === 0)
      ) {
        throw new CapaOperationEntropyUnavailableError();
      }
      bytes[6] = (bytes[6] & 0x0f) | 0x40;
      bytes[8] = (bytes[8] & 0x3f) | 0x80;
      const hex = Array.from(bytes, value =>
        value.toString(16).padStart(2, '0'),
      ).join('');
      const operationId = `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
      if (!isValidCapaOperationId(operationId)) {
        throw new CapaOperationEntropyUnavailableError();
      }
      return operationId;
    } catch {
      throw new CapaOperationEntropyUnavailableError();
    }
  }
  throw new CapaOperationEntropyUnavailableError();
}
